/**
 * Interface strings.
 *
 * English is the source: `MessageKey` is derived from the English table, and the
 * Chinese table is typed as `Record<MessageKey, string>`. That makes a missing
 * translation a **compile error** rather than a blank label at runtime — which
 * is the failure mode that otherwise only shows up when someone switches
 * language and hits the one screen nobody tested.
 *
 * Node and parameter text is *not* here. It comes from the backend catalogue so
 * that adding a node type stays a one-file change (see `app/graph/schema.py`);
 * duplicating it here would defeat that.
 *
 * Placeholders use `{name}` and are substituted by `translate`.
 */

