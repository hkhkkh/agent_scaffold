"""Inbound webhooks: the event-driven half of a trigger.

A webhook trigger is the same thing a schedule is — *a stored trigger plus a
workflow id* — with a different firing mechanism. A schedule fires on a clock; a
webhook fires when something POSTs to its token. Everything after that is shared:
the run it starts is an ordinary run, so it queues behind the same concurrency
limit, is bounded by the same budget, and appears in the same run history.

Why the token is in the path
-----------------------------

Posting to ``/api/hooks/<token>`` is what every comparable tool does (n8n, Zapier,
GitHub), and the reason is compatibility rather than taste: a URL is the one input
every system that can send a webhook is able to configure. A header-based scheme
would be marginally tidier and would exclude the tools that cannot set one.

The cost is real and worth stating: **the token appears in access logs and in
`Referer` headers.** Treat a hook URL as a credential — which the API does, by
never showing it after creation unless asked for explicitly.

Why this path is public
------------------------

An external system has no token of *ours*; the hook token is the whole of its
identification. So ``/api/hooks/`` is exempted from the auth middleware by prefix
(see ``PUBLIC_PREFIXES`` in ``app/security/auth.py``), and the security of this
endpoint rests entirely on the token being unguessable — 256 bits, generated by
``secrets.token_urlsafe``.

Three consequences that are deliberate, not oversights:

* **A disabled or orphaned trigger answers 404, not 403.** Telling an unauthorised
  caller "that hook exists but is off" hands them a valid token for free. Both
  cases are indistinguishable from a token that was never real.
* **Any method but POST is refused.** A GET would start runs from a browser
  prefetch or a link scanner.
* **No signature verification.** HMAC would require a shared secret on both sides,
  and most senders cannot do it. The token is the authentication; adding a
  signature check would be a second mechanism that half the callers cannot satisfy.
"""

from __future__ import annotations

from typing import Any

from fastapi import APIRouter, Body, HTTPException, Request, status

from app.scheduling import store
from app.scheduling.service import get_scheduler
from app.settings import get_settings

router = APIRouter(prefix="/hooks", tags=["hooks"])

#: Cap on a hook payload. A webhook body becomes a run's inputs, and those are
#: persisted, streamed to the UI, and passed to every node. An unbounded body is
#: therefore an unbounded write by an unauthenticated caller, which is the shape of
#: a denial-of-service rather than a feature. 64 KiB is far above anything a real
#: event carries and far below anything that hurts.
MAX_PAYLOAD_BYTES = 64 * 1024


@router.post(
    "/{token}",
    status_code=status.HTTP_202_ACCEPTED,
    summary="Start a run from an external event",
)
async def receive(token: str, request: Request) -> dict[str, Any]:
    """Start a run for this trigger and return its id immediately.

    202 rather than 201: the run is *accepted*, and the caller follows it with
    ``GET /api/runs/{id}`` if it cares. Waiting for the run would make an external
    system's request hang for as long as a workflow takes, and a workflow can wait
    on a person.

    The response body carries the run id and nothing else. Notably not the token:
    echoing a credential into a response that a sender may log is how it ends up
    in a third party's log files.
    """
    if get_settings().public_demo:
        # A valid hook token would start a run without passing the gate. The
        # operator can still trigger runs locally; the public surface cannot.
        raise HTTPException(status_code=404, detail="No such hook.")

    if request.headers.get("content-length"):
        try:
            length = int(request.headers["content-length"])
        except ValueError:
            length = 0
        if length > MAX_PAYLOAD_BYTES:
            raise HTTPException(
                status_code=413,
                detail=f"payload exceeds {MAX_PAYLOAD_BYTES} bytes.",
            )

    row = store.find_by_token(token)
    if row is None:
        # One answer for "never existed", "switched off" and "its workflow was
        # deleted" — see the module docstring. Not a 403 for the latter two.
        raise HTTPException(status_code=404, detail="No such hook.")

    body = await _body(request)
    try:
        run_id = await get_scheduler().fire_now(row, inputs=body)
    except Exception as exc:  # noqa: BLE001 - the reason is the caller's to see
        # 502 rather than 500: the request was well-formed and authorised, and what
        # failed is the platform's ability to act on it (usually a workflow that no
        # longer compiles). The trigger's row carries the same message for the
        # operator; the caller gets it because they are the one who can retry.
        raise HTTPException(status_code=502, detail=str(exc)) from exc

    return {"run_id": run_id, "trigger_id": row["id"]}


async def _body(request: Request) -> dict[str, Any]:
    """The request body as the run's inputs.

    A JSON object is used as-is; anything else — no body, an empty body, a
    non-object — becomes ``{}``. That is not leniency for its own sake: a sender
    that just needs "run this" will post nothing at all, and refusing it would
    make the simplest possible integration the one that does not work. An array or
    a scalar is dropped rather than wrapped, because a run's inputs are a mapping
    by contract and inventing a key for it would be guessing at the sender's
    intent.
    """
    try:
        payload = await request.json()
    except Exception:  # noqa: BLE001 - absent, empty, or not JSON: all mean "no inputs"
        return {}
    return payload if isinstance(payload, dict) else {}
